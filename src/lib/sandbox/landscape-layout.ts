import type { ArtworkRegion } from './artwork';
import type { Facility, Point, Surface } from './types';

/** Image-space teaching regions. These never replace SWMM polygons or areas. */
export interface LandscapeZone {
  id: number;
  boundary: Point[];
  label: Point;
  surfaces: Record<Exclude<Surface, 'reserved'>, Point[][]>;
  facilities: Record<Facility, ArtworkRegion[]>;
  markers: Record<Facility, Point>;
}

const box = (x: number, y: number, w: number, h: number): Point[] => [[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
function region(id: number, boundary: Point[], label: Point, roofs: Point[][], roads: Point[][], lawns: Point[][], garden: [number,number,number,number], swale: Point[]): LandscapeZone {
  const [gx,gy,gw,gh] = garden;
  const roof = roofs[0], road = roads[0];
  const center = (points: Point[]): Point => [points.reduce((s,p)=>s+p[0],0)/points.length,points.reduce((s,p)=>s+p[1],0)/points.length];
  return {
    id, boundary, label, surfaces: {roof: roofs, road: roads, green: lawns},
    facilities: {
      GR: roofs.map((polygon,i)=>({id:`z${id}-roof-${i}`,polygon})),
      PP: roads.map((polygon,i)=>({id:`z${id}-paving-${i}`,polygon})),
      RG: [{id:`z${id}-garden`,rect:garden}],
      VS: [{id:`z${id}-swale`,route:swale,width:7}],
    },
    markers: {GR:center(roof),PP:center(road),RG:[gx+gw/2,gy+gh/2],VS:center(swale)},
  };
}

